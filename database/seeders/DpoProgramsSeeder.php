<?php

namespace Database\Seeders;

use App\Models\DpoAnnouncement;
use App\Models\DpoAssignment;
use App\Models\DpoGroup;
use App\Models\DpoLesson;
use App\Models\DpoModule;
use App\Models\DpoProgram;
use App\Models\DpoScheduleEntry;
use Illuminate\Database\Seeder;

class DpoProgramsSeeder extends Seeder
{
    public function run(): void
    {
        foreach($this->catalog() as $programIndex=>$data){
            $program=DpoProgram::updateOrCreate(['slug'=>$data['slug']],[
                'code'=>$data['code'],
                'title'=>$data['title'],
                'hours'=>$data['hours'],
                'qualification'=>$data['qualification'],
                'document_type'=>'Удостоверение о повышении квалификации',
                'description'=>$data['description'],
                'learning_outcomes'=>implode("\n",array_map(fn($item)=>'• '.$item,$data['outcomes'])),
                'sort'=>100+($programIndex*10),
                'is_published'=>true,
                'is_archived'=>false,
                'applications_open'=>true,
                'min_progress_percent'=>100,
                'min_attendance_percent'=>70,
                'min_homework_percent'=>70,
                'min_scorm_percent'=>0,
            ]);

            $start=now()->startOfMonth()->addMonth()->addDays($programIndex*3+1)->startOfDay();
            $group=DpoGroup::updateOrCreate(
                ['program_id'=>$program->id,'name'=>'Набор 2026 / '.$data['code']],
                [
                    'starts_on'=>$start->toDateString(),
                    'ends_on'=>$start->copy()->addWeeks(8)->toDateString(),
                    'status'=>'draft',
                    'description'=>'Учебная группа ДПО. Материалы, задания и расписание доступны в личном кабинете.',
                ]
            );

            $lessonNumber=0;
            foreach($data['modules'] as $moduleIndex=>$moduleData){
                [$moduleTitle,$moduleDescription,$lessonTitles,$assignmentTask]=$moduleData;
                $module=DpoModule::updateOrCreate(
                    ['program_id'=>$program->id,'title'=>$moduleTitle],
                    ['description'=>$moduleDescription,'sort'=>($moduleIndex+1)*10,'is_published'=>true]
                );

                foreach($lessonTitles as $lessonIndex=>$lessonTitle){
                    $lessonNumber++;
                    $lesson=DpoLesson::updateOrCreate(
                        ['module_id'=>$module->id,'title'=>$lessonTitle],
                        [
                            'description'=>'Практический урок модуля «'.$moduleTitle.'»: '.$lessonTitle.'.',
                            'content'=>$this->lessonContent($program->title,$moduleTitle,$moduleDescription,$lessonTitle),
                            'duration_minutes'=>$data['hours']>=72?270:150,
                            'completion_mode'=>'view',
                            'sort'=>($lessonIndex+1)*10,
                            'is_published'=>true,
                        ]
                    );

                    $lessonStart=$start->copy()->addDays(($lessonNumber-1)*3)->setTime(9,0);
                    DpoScheduleEntry::updateOrCreate(
                        ['group_id'=>$group->id,'lesson_id'=>$lesson->id],
                        [
                            'teacher_user_id'=>null,
                            'title'=>$lessonTitle,
                            'starts_at'=>$lessonStart,
                            'ends_at'=>$lessonStart->copy()->addMinutes($lesson->duration_minutes),
                            'room'=>'Аудитория ДПО',
                            'online_url'=>null,
                            'notes'=>'Материалы и практическая часть находятся в личном кабинете ДПО.',
                        ]
                    );
                }

                $lastLesson=$module->lessons()->orderByDesc('sort')->first();
                if($lastLesson){
                    $assignment=DpoAssignment::updateOrCreate(
                        ['lesson_id'=>$lastLesson->id,'title'=>'Практическая работа №'.($moduleIndex+1).': '.$moduleTitle],
                        [
                            'description'=>"Итоговая работа по модулю «{$moduleTitle}».\n\n{$assignmentTask}\n\nПриложите результат: файл, скриншоты, схему, таблицу или краткий отчёт. Опишите ход выполнения и выводы.",
                            'max_score'=>100,
                            'allow_text'=>true,
                            'allow_file'=>true,
                            'is_published'=>true,
                        ]
                    );
                    $available=$start->copy()->addDays((($moduleIndex+1)*9)-3)->setTime(8,0);
                    $assignment->groups()->syncWithoutDetaching([
                        $group->id=>[
                            'available_from'=>$available,
                            'due_at'=>$available->copy()->addDays(7)->setTime(23,59),
                        ],
                    ]);
                }
            }

            DpoAnnouncement::updateOrCreate(
                ['program_id'=>$program->id,'group_id'=>$group->id,'title'=>'Добро пожаловать на программу'],
                [
                    'body'=>'Программа «'.$program->title.'» готова к обучению: 4 модуля, 12 уроков, 4 практические работы, расписание и условия итоговой аттестации.',
                    'published_at'=>now(),
                ]
            );
        }
    }

    private function lessonContent(string $program,string $module,string $moduleDescription,string $lesson): string
    {
        return '<h2>'.e($lesson).'</h2>'
            .'<p><strong>Цель урока:</strong> освоить тему «'.e($lesson).'» и научиться применять её в практических задачах программы «'.e($program).'».</p>'
            .'<p>'.e($moduleDescription).' В этом уроке рассматриваются назначение основных элементов и операций, последовательность выполнения работы, требования к результату и типовые ошибки.</p>'
            .'<h3>Что необходимо изучить</h3><ul>'
            .'<li>основные термины и назначение рассматриваемых элементов;</li>'
            .'<li>последовательность технологических или организационных действий;</li>'
            .'<li>исходные данные, параметры и ожидаемый результат;</li>'
            .'<li>контроль качества, диагностику ошибок и требования безопасной работы.</li>'
            .'</ul>'
            .'<h3>Практическая часть</h3><ol>'
            .'<li>Разберите рабочую ситуацию по теме урока и определите исходные данные.</li>'
            .'<li>Составьте последовательность действий или технологическую схему.</li>'
            .'<li>Определите контрольные точки, измеряемые параметры и возможные ошибки.</li>'
            .'<li>Сформулируйте вывод: по каким признакам можно считать работу выполненной правильно.</li>'
            .'</ol>'
            .'<h3>Самопроверка</h3><p>Объясните тему своими словами, перечислите ключевые этапы работы и назовите минимум три ошибки, которые необходимо исключить на практике.</p>'
            .'<div class="alert alert-primary"><strong>Модуль:</strong> '.e($module).'</div>';
    }


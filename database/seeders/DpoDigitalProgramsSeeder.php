class DpoDigitalProgramsSeeder extends Seeder
{
    public function run(): void
    {
        foreach($this->catalog() as $programIndex=>$data){
            $program=DpoProgram::updateOrCreate(['slug'=>$data['slug']],[
                'code'=>$data['code'],
                'title'=>$data['title'],
                'hours'=>$data['hours'],
                'qualification'=>$data['qualification'],
                'document_type'=>'Удостоверение о повышении квалификации',
                'description'=>$data['description'],
                'learning_outcomes'=>implode("\n",array_map(fn($item)=>'• '.$item,$data['outcomes'])),
                'sort'=>300+($programIndex*10),
                'is_published'=>true,
                'is_archived'=>false,
                'applications_open'=>true,
                'min_progress_percent'=>100,
                'min_attendance_percent'=>70,
                'min_homework_percent'=>70,
                'min_scorm_percent'=>0,
            ]);

            $start=now()->startOfMonth()->addMonth()->addDays(4+$programIndex*4)->startOfDay();
            $group=DpoGroup::updateOrCreate(
                ['program_id'=>$program->id,'name'=>'Набор 2026 / '.$data['code']],
                [
                    'starts_on'=>$start->toDateString(),
                    'ends_on'=>$start->copy()->addWeeks(8)->toDateString(),
                    'status'=>'draft',
                    'description'=>'Учебная группа ДПО. 4 модуля, 12 уроков и практические задания доступны в личном кабинете.',
                ]
            );

            $lessonNumber=0;
            foreach($data['modules'] as $moduleIndex=>$moduleData){
                [$moduleTitle,$moduleDescription,$lessonTitles,$assignmentTask]=$moduleData;
                $module=DpoModule::updateOrCreate(
                    ['program_id'=>$program->id,'title'=>$moduleTitle],
                    ['description'=>$moduleDescription,'sort'=>($moduleIndex+1)*10,'is_published'=>true]
                );

                foreach($lessonTitles as $lessonIndex=>$lessonTitle){
                    $lessonNumber++;
                    $lesson=DpoLesson::updateOrCreate(
                        ['module_id'=>$module->id,'title'=>$lessonTitle],
                        [
                            'description'=>'Практический урок: '.$lessonTitle.'.',
                            'content'=>$this->lessonContent($program->title,$moduleTitle,$moduleDescription,$lessonTitle),
                            'duration_minutes'=>270,
                            'lesson_type'=>$lessonIndex===2?'offline_practice':'online',
                            'completion_mode'=>$lessonIndex===2?'attendance':'view',
                            'sort'=>($lessonIndex+1)*10,
                            'is_published'=>true,
                        ]
                    );

                    $lessonStart=$start->copy()->addDays(($lessonNumber-1)*3)->setTime(9,0);
                    DpoScheduleEntry::updateOrCreate(
                        ['group_id'=>$group->id,'lesson_id'=>$lesson->id],
                        [
                            'teacher_user_id'=>null,
                            'title'=>$lessonTitle,
                            'starts_at'=>$lessonStart,
                            'ends_at'=>$lessonStart->copy()->addMinutes(270),
                            'room'=>'Лаборатория ДПО',
                            'online_url'=>null,
                            'notes'=>'Теория, практическая часть и материалы находятся в личном кабинете ДПО.',
                        ]
                    );
                }

                $lastLesson=$module->lessons()->orderByDesc('sort')->first();
                if($lastLesson){
                    $assignment=DpoAssignment::updateOrCreate(
                        ['lesson_id'=>$lastLesson->id,'title'=>'Практическая работа №'.($moduleIndex+1).': '.$moduleTitle],
                        [
                            'description'=>"Итоговая работа по модулю «{$moduleTitle}».\n\n{$assignmentTask}\n\nПриложите исходные файлы, скриншоты и краткий отчёт. Укажите ход выполнения, результат и выводы.",
                            'max_score'=>100,
                            'allow_text'=>true,
                            'allow_file'=>true,
                            'is_published'=>true,
                        ]
                    );
                    $available=$start->copy()->addDays((($moduleIndex+1)*9)-3)->setTime(8,0);
                    $assignment->groups()->syncWithoutDetaching([
                        $group->id=>[
                            'available_from'=>$available,
                            'due_at'=>$available->copy()->addDays(7)->setTime(23,59),
                        ],
                    ]);
                }
            }

            DpoAnnouncement::updateOrCreate(
                ['program_id'=>$program->id,'group_id'=>$group->id,'title'=>'Добро пожаловать на программу'],
                [
                    'body'=>'Программа «'.$program->title.'» полностью подготовлена: 4 модуля, 12 уроков, 4 практические работы, расписание и итоговые условия.',
                    'published_at'=>now(),
                ]
            );
        }
    }

    private function lessonContent(string $program,string $module,string $moduleDescription,string $lesson): string
    {
        return '<h2>'.e($lesson).'</h2>'
            .'<p><strong>Цель:</strong> освоить тему «'.e($lesson).'» и применить её в практической задаче программы «'.e($program).'».</p>'
            .'<p>'.e($moduleDescription).'</p>'
            .'<h3>Теоретическая часть</h3><ul>'
            .'<li>ключевые понятия, инструменты и назначение рассматриваемой технологии;</li>'
            .'<li>правильная последовательность выполнения работы и подготовка исходных данных;</li>'
            .'<li>требования к качеству результата и способы его проверки;</li>'
            .'<li>типовые ошибки, диагностика и безопасные способы их устранения.</li>'
            .'</ul>'
            .'<h3>Практика</h3><ol>'
            .'<li>Подготовьте рабочую среду, исходные материалы или проект.</li>'
            .'<li>Выполните основную операцию по теме урока поэтапно.</li>'
            .'<li>Проверьте результат и устраните обнаруженные ошибки.</li>'
            .'<li>Сохраните результат и зафиксируйте основные параметры работы.</li>'
            .'</ol>'
            .'<h3>Контрольные вопросы</h3><ol>'
            .'<li>Какие исходные данные необходимы для выполнения работы?</li>'
            .'<li>Какие этапы являются критическими для качества результата?</li>'
            .'<li>Как проверить правильность выполненной работы?</li>'
            .'<li>Какие типовые ошибки встречаются и как их диагностировать?</li>'
            .'</ol>'
            .'<div class="alert alert-primary"><strong>Модуль:</strong> '.e($module).'</div>';
    }

